  static const Map<AppLanguage, Locale> supportedLanguageLocales = {
    AppLanguage.en: Locale('en'),
    AppLanguage.pl: Locale('pl'),
    AppLanguage.nl: Locale('nl'),
    AppLanguage.tr: Locale('tr'),
    AppLanguage.bg: Locale('bg'),
    AppLanguage.el: Locale('el'),
  };

  static List<Locale> supportedLocales() {
    return supportedLanguageLocales.values.toList();
  }

  static AppLanguage fromLocale(Locale locale) {
    return supportedLanguageLocales.entries
            .firstWhere(
              (entry) => entry.value.languageCode == locale.languageCode,
              orElse: () => const MapEntry(AppLanguage.en, Locale('en')),
            )
            .key;
  }

