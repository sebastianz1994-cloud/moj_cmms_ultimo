    switch (language) {
      case AppLanguage.en:
        return '🇬🇧 English';
      case AppLanguage.pl:
        return '🇵🇱 Polski';
      case AppLanguage.nl:
        return '🇳🇱 Nederlands';
      case AppLanguage.tr:
        return '🇹🇷 Turkce';
      case AppLanguage.bg:
        return '🇧🇬 Balgarski';
      case AppLanguage.el:
        return '🇬🇷 Ellinika';
    }
  }

